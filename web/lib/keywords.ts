// 낱말 끝의 조사. "신혼부부의" → "신혼부부".
const PARTICLE = /(은|는|이|가|을|를|의|에|도|만|로|으로|에서|에게|께|와|과|랑|이랑)$/;

export function tokenize(q: string): string[] {
  return (q || "")
    .split(/[\s,·/]+/)
    .map((t) => t.trim())
    .map((t) => (t.length > 2 ? t.replace(PARTICLE, "") : t))
    .filter((t) => t.length >= 2 && !STOP.has(t) && !/^\d+$/.test(t))
    .slice(0, 4);
}

/** 낱말 하나를 동의어 묶음('전세|전월세|…')으로. 모르는 말은 그대로. */
export function expandWord(w: string): string {
  const hit = SYNONYMS.find((g) => g.some((s) => w.includes(s) || s.includes(w)));
  if (!hit) return w;
  // 원래 낱말도 남긴다 — 사전에 없는 변형("신혼 부부")을 놓치지 않으려고.
  return Array.from(new Set([w, ...hit])).join("|");
}

/** DB 에 보내는 모양. 비어 있으면 null. */
export function expandQuery(q?: string | null): string[] | null {
  const words = tokenize(q ?? "");
  if (!words.length) return null;
  return words.map(expandWord);
}

/** 화면에 되비출 낱말. 정리된 것만. */
export function cleanQuery(q?: string | null): string {
  return tokenize(q ?? "").join(" ");
}

