export const HELPER_CHIPS = HELPER_FAQ.filter((f) => f.chip);

/** 자유 입력에 가장 가까운 정해진 질문. 없으면 null. */
export function matchFaq(text: string): HelperFaq | null {
  const t = text.replace(/\s+/g, "");
  if (t.length < 2) return null;
  return HELPER_FAQ.find((f) => f.match.test(t)) ?? null;
}

/** "어디서 보나"를 묻는 질문들. 찾을 낱말이 같이 있으면("간호사 채용 어디서 봐요") 정해진 답 대신 그 낱말로 찾아 준다. */
