/**
 * 물어보는 말에서 찾을 낱말만 남긴다. "수원 간호사 채용 있어요?" → "수원 간호사".
 * 조사는 뜻이 안 바뀌는 것만 뗀다(은·는·을·를·에·에서·으로). "어린이"·"경기도"를 다치지 않게 이·가·도·로는 두었다.
 */
export function helperTerms(text: string): string {
  return text
    .replace(/[?!.,~…"'“”‘’()]/g, " ")
    .split(/\s+/)
    // 낱말 끝의 조사, 그리고 붙여 쓴 "간호사채용"의 꼬리.
    .map((w) => (w.length >= 3 ? w.replace(/(에서|에게|으로|은|는|을|를|에)$/, "") : w))
    .map((w) => (w.length >= 4 ? w.replace(/(채용공고|채용|공고|모집)$/, "") : w))
    // 낱말이 통째로 군말일 때만 뺀다. 안에 든 것은 건드리지 않는다("정보처리기사"의 정보).
    .filter((w) => w.length >= 2 && !NOISE.test(w))
    .slice(0, 5)
    .join(" ");
}

