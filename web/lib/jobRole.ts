/** 제목 괄호 안의 세부 분야. "기간제교사(영어)" → "영어". 없으면 null. */
export function detailOf(title: string): string | null {
  // 합격자·일정 같은 절차 낱말은 세부 분야가 아니다.
  const m = title.match(/[（(]([^()（）]{1,24})[)）]/);
  if (!m) return null;
  const s = m[1].trim();
  // "3차", "제2026-17호", "5명", "2026학년도" 는 분야가 아니다.
  if (/합격|전형|일정|공고|년도|학년도|^제?\s*[\d-]+\s*[차호]$|^\d+\s*명$/.test(s)) return null;
  return s;
}

export type Stage = "open" | "interview" | "final" | "repost" | "plan";

/**
 * 이 공고가 모집인지, 합격자 발표인지.
 *
 * 나라일터에는 채용 절차의 모든 단계가 같은 목록에 올라온다. "서류전형
 * 합격자 및 면접 일정" 을 보고 지원하려는 사람이 있어서, 제목에서 단계를
 * 읽어 먼저 말해 준다.
 */
export function stageOf(title: string): Stage {
  if (/최종\s*합격|합격자\s*발표|합격자\s*공고|채용\s*후보자/.test(title) && !/서류/.test(title)) return "final";
  if (/서류\s*(전형)?\s*합격|면접\s*(시험|전형|심사)?\s*(일정|안내|계획)|면접\s*대상/.test(title)) return "interview";
  if (/재공고|정정\s*공고|변경\s*공고/.test(title)) return "repost";
  if (/시행\s*계획|채용\s*계획|임용\s*(시험\s*)?계획|시험\s*계획/.test(title)) return "plan";
  return "open";
}

