/** 상품 이름이 "일반상환학자금_등록금" 처럼 붙어 있어 읽기 어렵다. */
export function productLabel(p: string) {
  const [a, b] = p.split("_");
  if (!b) return a;
  const use =
    b === "등록금생활비" ? "등록금·생활비" :
    b === "저금리전환" ? "저금리 전환" : b;
  return `${a === "일반상환학자금" ? "일반상환" : "취업후상환"} ${use}`;
}

export function loanBySido(sido: string) {
  return LOAN_ORGS.filter((o) => o.sido === sido);
}

/** 시·도별로 묶어서, 협약 기관이 많은 곳부터. */
export function loanGrouped() {
  const map = new Map<string, LoanOrg[]>();
  for (const o of LOAN_ORGS) {
    const list = map.get(o.sido) ?? [];
    list.push(o);
    map.set(o.sido, list);
  }
  return Array.from(map.entries())
    .map(([sido, orgs]) => ({ sido, orgs }))
    .sort((a, b) => b.orgs.length - a.orgs.length || a.sido.localeCompare(b.sido, "ko"));
}
