/** 따옴표 엔터티("&#034;마&#034;급")와 기관 이름 낱말을 지운 읽을 글. */
function textOf(j: ClassInput): string {
  let title = j.title;
  for (const w of (j.org ?? "").split(/[\s()]+/)) if (w.length >= 2) title = title.split(w).join(" ");
  return `${title} ${j.post ?? ""} ${j.kind ?? ""}`
    .replace(/&#0?34;|&quot;|["“”'‘’]/g, "")
    .replace(/\s+/g, " ");
}

function gradesOf(t: string): string[] {
  const out = new Set<number>();
  const add = (n: number) => { if (n >= 1 && n <= 9) out.add(n); };
  // "8-9급", "특정5~7급"
  for (const m of t.matchAll(/([1-9])\s*[~∼\-–]\s*([1-9])\s*급/g)) {
    if (NOT_RANK.test(t.slice(Math.max(0, m.index! - 10), m.index))) continue;
    const [a, b] = [Number(m[1]), Number(m[2])].sort((x, y) => x - y);
    for (let n = a; n <= b; n++) add(n);
  }
  for (const m of t.matchAll(/([1-9])\s*급/g)) {
    if (NOT_RANK.test(t.slice(Math.max(0, m.index! - 10), m.index))) continue;
    add(Number(m[1]));
  }
  for (const [re, n] of RANKS) if (re.test(t)) add(n);
  const labels = [...out].sort((a, b) => a - b).map((n) => (n <= 4 ? "4급 이상" : `${n}급`));
  // 임기제 가~마급. "가급적" 은 급수가 아니다.
  if (/임기/.test(t)) for (const m of t.matchAll(/([가나다라마])\s*급(?!적)/g)) labels.push(`임기제 ${m[1]}급`);
  return [...new Set(labels)];
}

const memo = new WeakMap<object, JobClass>();

export function classifyJob(j: ClassInput): JobClass {
  const hit = memo.get(j);
  if (hit) return hit;
  const t = textOf(j);
  const types = TYPE_RULES.filter(([, re]) => re.test(t)).map(([v]) => v);
  if (!types.includes("임기제") && OFFICIAL.test(t)) types.push("공무원");
  const sectors = (j.sectors ?? "").split(/,\s*/).map((s) => s.trim()).filter(Boolean);
  const fields = FIELD_RULES.filter(([, re, ncs]) => re.test(t) || ncs.some((n) => sectors.includes(n))).map(([v]) => v);
  const ordered = JOB_TYPES.map((x) => x.v).filter((v) => types.includes(v));
  const out: JobClass = {
    types: ordered,
    // 급수는 공무원·임기제 자리에서만 읽는다. 공공기관·병원의 자체 직급("약무4급", "직무급제 4급", "무기계약직 3등급")은
    // 공무원 급수와 뜻이 달라, 6급을 고른 사람에게 섞여 나오면 헷갈린다.
    grades: ordered.includes("공무원") || ordered.includes("임기제") ? gradesOf(t) : [],
    fields,
  };
  memo.set(j, out);
  return out;
}
