// ── '정부 복지' 로 찾아 들어오는 분들을 위한 안내 ─────────────
//
// 지역마다 같은 문장을 쓰면 검색엔진이 중복으로 보고 어느 쪽도 잘 띄우지
// 않는다. 그래서 지역 이름과 그 지역의 실제 집계를 문장 안에 넣어,
// 페이지마다 다른 글이 되도록 만든다.

export type AreaStat = { label: string; n: number };

/** 이 지역에서 가장 두꺼운 갈래. 문장에 넣어 페이지마다 다르게 만든다. */
function topLabel(stats: AreaStat[]) {
  const t = [...stats].sort((a, b) => b.n - a.n)[0];
  return t && t.n > 0 ? t.label.replace(" 대상", "").replace(" 가구", "") : null;
}

/** 약 300자. "지역명 + 정부 복지" 와 "정부복지" 가 자연스럽게 들어간다. */
export function govWelfare(sido: string, n: number, stats: AreaStat[]) {
  const top = topLabel(stats);
  return (
    `${sido} 정부 복지는 중앙부처가 전국에 시행하는 제도와 ${sido} 및 그 아래 ` +
    `시·군·구가 자체 예산으로 운영하는 사업이 겹쳐 있습니다. 창구가 서로 다르고 ` +
    `공고도 따로 나기 때문에, 정부복지 라는 한 단어로 검색해서는 내게 해당되는 것을 ` +
    `추리기가 어렵습니다. 이 화면은 그 둘을 한자리에 모아 두고, 사는 곳과 나이 같은 ` +
    `조건을 넣으면 해당될 만한 것만 남깁니다. 현재 ${sido}에서 조건을 확인할 수 있는 ` +
    `사업은 ${n}건이고, ` +
    (top
      ? `그 가운데 ${top} 쪽이 가장 두껍습니다. `
      : "대상별로 나누어 볼 수 있습니다. ") +
    `회원가입도 주민등록번호도 필요 없고, 넣으신 조건은 저장하지 않습니다. ` +
    `${sido} 정부 복지를 처음 알아보시는 분이라면 아래 활용 방법과 신청 방법을 ` +
    `먼저 읽어 보시면 헤매는 시간이 줄어듭니다.`
  );
}

