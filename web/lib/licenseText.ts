export function seriesRole(series: string) {
  return ROLE[series] ?? "개별 법령에 따라 시행되는 자격입니다. 응시 자격과 시험 방식이 종목마다 다르므로 시행 기관의 안내를 따릅니다.";
}

export function seriesEligibility(series: string) {
  return ELIG[series] ?? ["종목별 법령과 시행 기관 공고에 따릅니다."];
}

export function licenseIntro(l: License) {
  const s = l.series;
  const kind = l.kind === "T" ? "국가기술자격" : l.kindName || "국가자격";
  return `${l.name}은(는) ${l.field}${l.subField ? ` 가운데 ${l.subField}` : ""} 분야의 ${kind}${ELIG[s] ? ` ${s} 등급` : ""}입니다. ${seriesRole(s)}`;
}

export function licenseFaq(l: License): QA[] {
  const s = l.series;
  return [
    { q: `${l.name} 시험은 누가 볼 수 있나요?`, a: ELIG[s] ? (s === "기능사" ? "응시 자격 제한이 없습니다. 학력이나 경력 없이 누구나 접수할 수 있습니다." : `${s} 등급의 일반 기준을 따릅니다. ${ELIG[s].slice(0, 2).join(", ")} 등이 대표적이고, 종목별 예외는 큐넷 종목 안내에서 확인하세요.`) : "종목별 법령에 따릅니다. 시행 기관의 공고에서 응시 자격을 확인하세요." },
    { q: "시험 일정은 어디서 확인하나요?", a: "큐넷(q-net.or.kr)의 종목별 시험 일정에서 봅니다. 대부분 필기·실기로 나뉘어 한 해에 여러 회차가 있고, 접수는 회차마다 며칠만 받습니다." },
    { q: "학원비나 응시료를 지원받을 수 있나요?", a: "국민내일배움카드에 등록된 훈련과정이면 훈련비 상당 부분을 지원받습니다. 지자체마다 청년 자격증 응시료 지원과 합격 장려금 사업이 있으니 사는 곳과 나이를 넣고 조회해 보세요." },
    { q: "이 자격증으로 어떤 채용에 지원하나요?", a: `공공기관 채용 화면에서 '${l.field}' 분야 공고를 걸러 보세요. 기술직 공고는 자격 요건에 등급을 명시하는 경우가 많습니다.` },
  ];
}
